# ==============================================================================
# FILE: backend/apps/predictions/models.py
# PURPOSE: Database schema models for persistent storage of AI disease predictions, TreeSHAP attributions, and symptom NLP logs.
# VIVA EXPLANATION: Persists immutable diagnostic prediction logs mandated by FDA SaMD and EU MDR clinical software standards. Stores model metadata, raw input vectors, probability scores, triage urgency tiers, and TreeSHAP waterfall feature attributions for forensic traceability.
# ==============================================================================

from django.conf import settings
from django.db import models


# --- DiseasePrediction ---
# What it does: Stores an immutable clinical prediction generated by the AI inference engine.
# Why it's structured this way: Captures complete auditability parameters (model_name, model_version, inputs, TreeSHAP explanation JSON).
# Parameters & Returns: Django Model representing disease predictions.
# ------------------------------------------------------------------------------
class DiseasePrediction(models.Model):
    """
    Stores an immutable clinical prediction generated by the AI inference engine.

    Fields:
        - patient (ForeignKey): Target patient user receiving the clinical assessment.
          Enforces multi-tenancy and doctor-patient access authorization boundaries.
        - model_name (CharField): Identifies the serving AI architecture (e.g., 'MediCare-MultiDisease-XGBoost').
        - model_version (CharField): Semantic version of the trained model artifacts (e.g., '2.0.0').
        - input_data (JSONField): Input snapshot containing canonical symptoms, raw text, and vital signs.
        - predicted_condition (CharField): Highest probability diagnosis identified by the engine.
        - confidence (FloatField): Calibrated probability score (0.0 to 1.0) for the top condition.
        - explanation (JSONField): Complete TreeSHAP attributions, triage level, severity, and clinical guidance.
        - created_at (DateTimeField): Immutable timestamp indexed for rapid timeline queries.
    """
    patient = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="disease_predictions",
        help_text="Patient user associated with this clinical prediction.",
    )
    model_name = models.CharField(
        max_length=100,
        help_text="Name of the AI model architecture used for inference.",
    )
    model_version = models.CharField(
        max_length=50,
        blank=True,
        help_text="Semantic artifact version (e.g. 2.0.0) for MLOps traceability.",
    )
    input_data = models.JSONField(
        default=dict,
        help_text="Snapshot of clinical inputs (symptoms and vitals) at inference time.",
    )
    predicted_condition = models.CharField(
        max_length=200,
        blank=True,
        help_text="Primary disease condition predicted by the CDSS engine.",
    )
    confidence = models.FloatField(
        null=True,
        blank=True,
        help_text="Calibrated confidence probability score (0.0 to 1.0).",
    )
    explanation = models.JSONField(
        default=dict,
        blank=True,
        help_text="Structured TreeSHAP feature attributions, triage severity, and clinical recommendations.",
    )
    created_at = models.DateTimeField(
        auto_now_add=True,
        db_index=True,
        help_text="Timestamp of prediction generation.",
    )

    class Meta:
        ordering = ["-created_at"]
        indexes = [
            models.Index(fields=["patient", "-created_at"]),
        ]
        verbose_name = "Disease Prediction"
        verbose_name_plural = "Disease Predictions"

    def __str__(self):
        return f"Prediction for {self.patient.email}: {self.predicted_condition} ({self.created_at:%Y-%m-%d})"


# --- SymptomAnalysis ---
# What it does: Stores historical symptom NLP parsing sessions, extracted canonical tags, and suggestions.
# Why it's structured this way: Preserves symptom intake context to track clinical presentation evolution across consultations.
# Parameters & Returns: Django Model representing symptom analysis sessions.
# ------------------------------------------------------------------------------
class SymptomAnalysis(models.Model):
    """
    Stores historical symptom NLP parsing sessions.

    Fields:
        - patient (ForeignKey): Patient user who submitted the clinical inquiry.
        - symptoms_text (TextField): Raw patient-reported symptom narrative or query.
        - result (JSONField): Canonical symptoms, negated symptoms, and suggested co-occurrences.
        - created_at (DateTimeField): Audit timestamp for historical analysis tracking.
    """
    patient = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name="symptom_analyses",
        help_text="Patient user who performed the symptom analysis.",
    )
    symptoms_text = models.TextField(
        help_text="Raw natural language text or symptom tokens submitted by the patient.",
    )
    result = models.JSONField(
        default=dict,
        blank=True,
        help_text="Extracted canonical symptoms, negated symptoms, and co-occurring recommendations.",
    )
    created_at = models.DateTimeField(
        auto_now_add=True,
        db_index=True,
        help_text="Timestamp of symptom analysis.",
    )

    class Meta:
        ordering = ["-created_at"]
        verbose_name = "Symptom Analysis"
        verbose_name_plural = "Symptom Analyses"
        indexes = [
            models.Index(fields=["patient", "-created_at"]),
        ]

    def __str__(self):
        return f"SymptomAnalysis for {self.patient.email} at {self.created_at:%Y-%m-%d}"


# Canonical alias for Part 2 specification compatibility
DiseasePredictionHistory = DiseasePrediction
